// Arithmetic operators
let x = 10;
let y = 5;
let z = x + y; // Addition
console.log(z);

let a = 10;
let b = 5;
let c = a - b; // Subtraction
console.log(c);

let d = 10;
let e = 5;
let f = d * e; // Multiplication
console.log(f);

let g = 10;
let h = 5;
let i = g / h; // Division
console.log(i);

let j = 10;
let k = 5;
let l = j % k; // Modulus
console.log(l);

// Increment
let m = 10;
m++;
console.log(m);

// Decrement
let n = 10;
n--;
console.log(n);

// exponentiation
let o = 2;
let p = 3;
let q = o ** p;
console.log(q);

// Assignment operators
let r = 10;
r += 5;
console.log(r);
r -= 3;
console.log(r);
r *= 2;
console.log(r);
r /= 4;
console.log(r);
r %= 3;
console.log(r);
r **= 2;
console.log(r);

// Comparison operators
let s = 10;
let t = 5;
console.log(s == t); // equal to
console.log(s != t); // not equal to
console.log(s > t); // greater than
console.log(s < t); // less than
console.log(s >= t); // greater than or equal to
console.log(s <= t); // less than or equal to
console.log(s === t); // strict equal to
console.log(s !== t); // strict not equal to

// Logical operators
let u = true;
let v = false;
console.log(u && v); // logical AND
console.log(u || v); // logical OR
console.log(!u); // logical NOT


// Bitwise operators
let w = 5;

// Bitwise AND
let x1 = 3;
console.log(w & x1); // 1

