// conditional assignment

let a = 10;
let b = 5;
let ans = (a > b) ? "True" : "False";
console.log(ans); 

// checking if a string is equal to another string:
let str1 = "hello";
let str2 = "world";
let ans1 = (str1 === str2) ? "True" : "False";
console.log(ans1);

// checking if a varible is a number or not:
let score = "100";
let ans2 = (score) ? "Not a number" : "Is a number";
console.log(ans2);

// checking if a boolean value is true or false:
let isLoggedIn = true;
let ans3 = (isLoggedIn) ? "True" : "False";
console.log(ans3);